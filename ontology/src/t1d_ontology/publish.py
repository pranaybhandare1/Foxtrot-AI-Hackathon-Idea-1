"""Publish the ontology after validation.

- data/warehouse.duckdb: schemas raw / transformed / clean (one view per dataset) and
  ontology (one view per object type, e.g. ontology."Meal"), for any SQL client
- data/reports/ontology_catalog.md: generated catalog with an ER diagram
"""

from __future__ import annotations

import duckdb
from t1d_core.settings import Config

from t1d_ontology.actions import ensure_tables
from t1d_ontology.model import Ontology, load
from t1d_ontology.validation import OntologyValidationError, validate


def publish_warehouse(ont: Ontology, cfg: Config) -> None:
    L = cfg.layers
    con = duckdb.connect(str(L.warehouse))
    for schema, folder in (
        ("raw", L.raw),
        ("transformed", L.transformed),
        ("clean", L.clean),
        ("writeback", L.writeback),
    ):
        con.execute(f"CREATE SCHEMA IF NOT EXISTS {schema}")
        for f in sorted(folder.glob("*.parquet")):
            con.execute(f"CREATE OR REPLACE VIEW {schema}.{f.stem} AS SELECT * FROM read_parquet('{f}')")
    con.execute("CREATE SCHEMA IF NOT EXISTS ontology")
    for ot in ont.object_types.values():
        con.execute(f"CREATE OR REPLACE VIEW ontology.\"{ot.name}\" AS SELECT * FROM read_parquet('{ot.path(L.root)}')")
    con.close()


def write_catalog(ont: Ontology, cfg: Config, result: dict) -> None:
    lines = [
        f"# Ontology catalog: `{ont.name}` v{ont.version}",
        "",
        "_Generated by `t1d run` from `ontology/ontology.yaml`. Do not edit by hand._",
        "",
        "```mermaid",
        "erDiagram",
    ]
    for lt in ont.link_types.values():
        lines.append(f'    {lt.one} ||--o{{ {lt.many} : "{lt.name}"')
    lines += ["```", "", "| Object type | Kind | Primary key | Rows | Backing dataset |", "|---|---|---|---|---|"]
    for ot in ont.object_types.values():
        kind = "dataset" if ot.is_dataset else "object"
        lines.append(
            f"| {ot.name} | {kind} | `{ot.primary_key}` | {result['rows'].get(ot.name, '-'):,} | `{ot.backing_dataset}` |"
        )
    for ot in ont.object_types.values():
        lines += ["", f"## {ot.name}", "", ot.description, ""]
        links = ont.links_of(ot.name)
        if links:
            lines.append(
                "**Links:** "
                + ", ".join(
                    f"`{lt.name}` → {lt.one if lt.many == ot.name else lt.many}"
                    + (f" ({result['links'][lt.name]['linked']:,} linked)" if lt.name in result["links"] else "")
                    for lt in links
                )
            )
            lines.append("")
        lines += ["| Property | Type | Description |", "|---|---|---|"]
        for p in ot.properties.values():
            key = " (PK)" if p.name == ot.primary_key else ""
            lines.append(f"| `{p.name}`{key} | {p.type} | {p.description} |")
    cfg.reports_dir.mkdir(parents=True, exist_ok=True)
    (cfg.reports_dir / "ontology_catalog.md").write_text("\n".join(lines) + "\n")


def build(cfg: Config) -> dict:
    ont = load()
    ensure_tables(ont, cfg)
    result = validate(ont, cfg)
    if result["errors"]:
        raise OntologyValidationError("Ontology validation failed:\n  " + "\n  ".join(result["errors"]))
    publish_warehouse(ont, cfg)
    write_catalog(ont, cfg, result)
    return {
        "object_types": len(ont.object_types),
        "link_types": len(ont.link_types),
        "objects": sum(v for k, v in result["rows"].items() if not ont.object_types[k].is_dataset),
        "warehouse": str(cfg.layers.warehouse),
    }
